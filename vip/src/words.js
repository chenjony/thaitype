export function generateVipWords(count = 500) {
  const result = []
  let deck = []
  while (result.length < count) {
    if (deck.length === 0) deck = [...THAI_COMMON_WORDS].sort(() => Math.random() - 0.5)
    result.push(deck.pop())
  }
  return result.join(' ')
}
